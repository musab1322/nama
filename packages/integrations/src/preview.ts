import type { ProjectFiles } from "@banna/shared/snapshots";

/**
 * Preview builds (ADR-010): the app runs on a database inside the browser. The
 * platform writes lib/preview/config.ts with the app's migrations and demo data;
 * production builds keep the template's file, where PREVIEW is false.
 */
export const PREVIEW_CONFIG_PATH = "src/lib/preview/config.ts";
export const PREVIEW_SEED_PATH = "preview/seed.sql";
const MIGRATIONS_DIR = "supabase/migrations/";

export function withPreviewConfig(files: ProjectFiles): ProjectFiles {
  const migrations = Object.keys(files)
    .filter((p) => p.startsWith(MIGRATIONS_DIR) && p.endsWith(".sql"))
    .sort()
    .map((p) => ({ name: p.slice(MIGRATIONS_DIR.length, -4), sql: files[p]! }));
  const seed = files[PREVIEW_SEED_PATH] ?? "";
  const config = `// Generated by the platform for a preview build. Do not edit.
export const PREVIEW = true;
export const PREVIEW_MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};
export const PREVIEW_SEED = ${JSON.stringify(seed)};
`;
  return { ...files, [PREVIEW_CONFIG_PATH]: config };
}
